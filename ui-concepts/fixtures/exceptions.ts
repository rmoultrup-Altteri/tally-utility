/** Consequence ordering: severity first, then money at risk. */
const SEVERITY_RANK: Record<Exception['severity'], number> = {
  critical: 0,
  high: 1,
  medium: 2,
  low: 3,
}

export function byConsequence(rows: Exception[]): Exception[] {
  return [...rows].sort((a, b) => {
    const rank = SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity]
    if (rank !== 0) return rank
    return Number(b.estimated_impact ?? 0) - Number(a.estimated_impact ?? 0)
  })
}

